#!/usr/bin/env python3
"""
run_plip_analysis.py

Batch processes top docking poses through PLIP to extract non-covalent
interactions across all 5 ligands and 2 receptor targets (10 conditions total).

Fix history (2026-08-24):
  - PLIP was being invoked via `python -m plip.cli` in a *separate*
    subprocess, so the pybel.Molecule.write("inchikey") monkeypatch defined
    in this file never applied to that process -> every condition crashed
    inside PLIP with `ValueError: inchikey is not a recognised Open Babel
    format`, silently reported upstream as "XML result generation failed".
  - Fix: the patch now lives in a tiny standalone runner script
    (_plip_runner.py, auto-written next to this file) that PLIP's subprocess
    actually executes, so the patch is applied *before* PLIP's own main()
    runs in that process. That entrypoint is plip.plipcmd.main, not
    plip.cli.main -- this PLIP install has no plip.cli module at all.
  - All paths handed to the subprocess are resolved to absolute paths, since
    PLIP's own internal path handling on Windows has been unreliable with
    relative paths.
"""

import json
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

PROCESSED_DIR = Path("data/processed")
RECEPTOR_DIR = PROCESSED_DIR / "receptors"
RESULTS_DIR = PROCESSED_DIR / "docking_results"

BASE_PLIP_DIR = Path("results/plip_results")
PLIP_JSON_OUT = Path("results/plip_analysis/plip_analysis_results.json")

SCRIPT_DIR = Path(__file__).resolve().parent
PLIP_RUNNER_PATH = SCRIPT_DIR / "_plip_runner.py"

# Standalone script PLIP actually runs in its own subprocess. Applying the
# pybel monkeypatch has to happen *inside that process*, before plip.cli
# imports/uses pybel -- doing it only in this file has no effect on the
# subprocess PLIP runs in.
_PLIP_RUNNER_SOURCE = '''\
"""
Auto-generated by run_plip_analysis.py. Do not edit by hand -- regenerated
on every run. Applies the inchikey monkeypatch, then hands off to PLIP's
own CLI entrypoint with the original argv untouched.
"""
from openbabel import pybel

_original_write = pybel.Molecule.write


def _patched_write(self, format="smi", filename=None, overwrite=False):
    if format.lower() == "inchikey":
        try:
            return _original_write(self, format, filename, overwrite)
        except ValueError:
            try:
                from rdkit import Chem
                from rdkit.Chem import inchi
                smi = self.write("smi").split()[0]
                mol = Chem.MolFromSmiles(smi)
                if mol:
                    return inchi.MolToInchiKey(mol)
            except Exception:
                pass
            return "PLIP_INCHIKEY_PLACEHOLDER"
    return _original_write(self, format, filename, overwrite)


pybel.Molecule.write = _patched_write

# NOTE: this installed PLIP version's CLI entrypoint lives in plip.plipcmd
# (confirmed from the earlier traceback showing .../plip/plipcmd.py, line 417,
# in main), not plip.cli -- that module does not exist in this install.
from plip.plipcmd import main

if __name__ == "__main__":
    main()
'''


def ensure_plip_runner():
    """Writes/refreshes the standalone PLIP runner script next to this file."""
    PLIP_RUNNER_PATH.write_text(_PLIP_RUNNER_SOURCE, encoding="utf-8")


def convert_pdbqt_to_pdb(pdbqt_path, pdb_path):
    """Converts top docking pose PDBQT to standard PDB format using PyBel with explicit hydrogens."""
    try:
        from openbabel import pybel
        mol = next(pybel.readfile("pdbqt", str(pdbqt_path)))
        mol.addh()
        mol.write("pdb", str(pdb_path), overwrite=True)
        return True
    except Exception as e:
        print(f"  [-] PyBel conversion error: {e}")
        return False


def combine_receptor_and_ligand(receptor_file, ligand_pdb, complex_pdb):
    """
    Combines receptor and ligand into a clean, PLIP-compliant complex PDB file.

    NOTE: earlier version rebuilt each ligand HETATM line from scratch via
    string concatenation, which did not reliably land resName/chain/resSeq in
    PDB's strict fixed columns (18-20 / 22 / 23-26). PLIP silently found zero
    ligands as a result (rc=0, "finished analysis", but no report written).
    Fix: ligand_pdb is already well-formed (written by OpenBabel), so only
    patch the resName/chain/resSeq columns on the existing line instead of
    reconstructing it, preserving OpenBabel's correct serial/atom-name/coord
    formatting.
    """
    with open(complex_pdb, "w", encoding="utf-8") as out_f:
        if Path(receptor_file).exists():
            with open(receptor_file, "r", encoding="utf-8") as r_f:
                for line in r_f:
                    if line.startswith(("ATOM", "HETATM")):
                        out_f.write(line.rstrip("\n").ljust(80) + "\n")

        with open(ligand_pdb, "r", encoding="utf-8") as l_f:
            for line in l_f:
                if line.startswith(("ATOM", "HETATM")):
                    line = line.rstrip("\n").ljust(80)
                    # cols:   1-6      7-17(serial+space+atomname+altLoc)  18-20(resName)  21(blank)  22(chain)  23-26(resSeq)  27-...(rest unchanged)
                    new_line = (
                        "HETATM"
                        + line[6:17]
                        + "LIG"
                        + line[20:21]
                        + "L"
                        + " 1  "
                        + line[26:]
                    )
                    out_f.write(new_line[:80] + "\n")

        out_f.write("END\n")


def analyze_with_plip_cli(complex_pdb, condition_key, output_dir):
    """
    Runs PLIP in a subprocess via the auto-generated _plip_runner.py wrapper
    (not `python -m plip.cli` directly), so the inchikey monkeypatch is
    applied inside the process that actually runs PLIP.
    """
    complex_pdb = Path(complex_pdb).resolve()
    output_dir = Path(output_dir).resolve()

    cmd = [
        sys.executable, str(PLIP_RUNNER_PATH),
        "-f", str(complex_pdb),
        "-o", str(output_dir),
        "-x",  # Output XML report
    ]

    result = subprocess.run(cmd, capture_output=True, text=True)

    # This PLIP version names its XML output "<input_stem>_report.xml"
    # (e.g. wildtype_afatinib_complex_report.xml), not the generic
    # "report.xml" originally assumed here -- confirmed via the diagnostic
    # directory listing below, which showed the real filename PLIP wrote.
    default_xml = output_dir / f"{complex_pdb.stem}_report.xml"
    target_xml = output_dir / f"{condition_key}.xml"

    if not default_xml.exists():
        print(f"  [PLIP return code] {result.returncode}")
        if result.stdout.strip():
            print(f"  [PLIP stdout]\n{result.stdout}")
        if result.stderr.strip():
            print(f"  [PLIP stderr]\n{result.stderr}")
        # Diagnostic: PLIP can exit 0 with "finished analysis" yet write
        # nothing if it found zero valid ligands in the complex. Show what
        # (if anything) actually landed in output_dir so a naming mismatch
        # vs. a "no ligand detected" case are easy to tell apart.
        existing = sorted(p.name for p in output_dir.glob(f"{condition_key}*"))
        print(f"  [output_dir contents matching '{condition_key}*'] {existing or '(none)'}")
        return None

    if target_xml.exists():
        target_xml.unlink()
    shutil.move(str(default_xml), str(target_xml))
    return target_xml


def parse_plip_xml(xml_path):
    """Parses PLIP XML output for hydrogen bonds and hydrophobic interactions."""
    tree = ET.parse(xml_path)
    root = tree.getroot()

    interactions = {
        "h_bonds": [],
        "hydrophobic": [],
        "total_interactions": 0
    }

    for hb in root.findall(".//hydrogen_bonds/hydrogen_bond"):
        res_nr = hb.find("resnr").text if hb.find("resnr") is not None else ""
        res_type = hb.find("restype").text if hb.find("restype") is not None else ""
        dist = hb.find("dist_d-a").text if hb.find("dist_d-a") is not None else ""
        interactions["h_bonds"].append({
            "residue": f"{res_type}{res_nr}",
            "distance_angstrom": float(dist) if dist else None
        })

    for hp in root.findall(".//hydrophobic_interactions/hydrophobic_interaction"):
        res_nr = hp.find("resnr").text if hp.find("resnr") is not None else ""
        res_type = hp.find("restype").text if hp.find("restype") is not None else ""
        dist = hp.find("dist").text if hp.find("dist") is not None else ""
        interactions["hydrophobic"].append({
            "residue": f"{res_type}{res_nr}",
            "distance_angstrom": float(dist) if dist else None
        })

    interactions["total_interactions"] = len(interactions["h_bonds"]) + len(interactions["hydrophobic"])
    return interactions


def diagnose_zero_interactions(xml_path, complex_pdb):
    """
    Only called when total_interactions == 0, to distinguish two very
    different root causes without another round trip:
      (a) parse_plip_xml is looking for the wrong tag names for this PLIP
          version's XML schema (report has data, we're just not reading it)
      (b) PLIP genuinely found zero contacts, most likely because the
          ligand and receptor atoms in complex_pdb are not actually close
          together in space (a coordinate-frame / file-mismatch problem).
    """
    # (a) Dump every distinct tag name actually present in the report, plus
    # how many <bindingsite> blocks exist, so a schema mismatch is obvious.
    tree = ET.parse(xml_path)
    root = tree.getroot()
    all_tags = sorted({elem.tag for elem in root.iter()})
    n_bindingsites = len(root.findall(".//bindingsite"))
    print(f"  [diag] bindingsite elements found: {n_bindingsites}")
    print(f"  [diag] all distinct XML tags in report: {all_tags}")

    # (b) Compute the minimum distance between any LIG atom and any
    # receptor (non-LIG) atom directly from the complex PDB coordinates.
    # PLIP's default interaction cutoffs are all under ~4.5 A, so a minimum
    # distance much larger than that means the two aren't in contact at all
    # regardless of what PLIP's parser does.
    lig_coords = []
    rec_coords = []
    with open(complex_pdb, "r", encoding="utf-8") as f:
        for line in f:
            if line.startswith(("ATOM", "HETATM")):
                try:
                    x = float(line[30:38])
                    y = float(line[38:46])
                    z = float(line[46:54])
                except ValueError:
                    continue
                resname = line[17:20].strip()
                (lig_coords if resname == "LIG" else rec_coords).append((x, y, z))

    if not lig_coords or not rec_coords:
        print(f"  [diag] ligand atoms parsed: {len(lig_coords)}, receptor atoms parsed: {len(rec_coords)} "
              f"-- one side is empty, that alone would explain zero interactions")
        return

    min_dist = min(
        ((lx - rx) ** 2 + (ly - ry) ** 2 + (lz - rz) ** 2) ** 0.5
        for lx, ly, lz in lig_coords
        for rx, ry, rz in rec_coords
    )
    print(f"  [diag] ligand atoms: {len(lig_coords)}, receptor atoms: {len(rec_coords)}, "
          f"min ligand-receptor atom distance: {min_dist:.2f} A")
    if min_dist > 5.0:
        print("  [diag] >5 A minimum distance -- ligand and receptor are not in contact in this file; "
              "likely a coordinate-frame mismatch between the receptor file and the docked pose used")


def organize_plip_results(base_dir, receptors, ligands):
    """Organizes output files into clean directory tree: results/plip_results/{receptor}/{drug}/"""
    for rec in receptors:
        for lig in ligands:
            condition_key = f"{rec}_{lig}"
            target_dir = base_dir / rec / lig
            target_dir.mkdir(parents=True, exist_ok=True)

            matching_files = list(base_dir.glob(f"{condition_key}*.*"))
            for file_path in matching_files:
                if file_path.is_file():
                    dest = target_dir / file_path.name
                    shutil.move(str(file_path), str(dest))


def find_best_pose_pdbqt(pdbqt_dir, rec, lig):
    """
    Finds the best-scoring pose (most negative Vina binding affinity) across
    all seed*.pdbqt files for this condition, instead of assuming any one
    seed (e.g. seed1) is representative.

    Vina's PDBQT output records affinity in the first "REMARK VINA RESULT:"
    line of the file, e.g.:
        REMARK VINA RESULT:    -8.2      0.000      0.000
    The first number is the predicted binding affinity in kcal/mol (more
    negative = better). This scans every seed file for that condition and
    returns the path with the lowest value.

    Returns (best_path, best_affinity) or (None, None) if no seed files or
    no parseable affinity were found.
    """
    candidates = sorted(pdbqt_dir.glob(f"{rec}_{lig}_seed*.pdbqt"))
    if not candidates:
        return None, None

    best_path, best_affinity = None, None
    for path in candidates:
        try:
            with open(path, "r", encoding="utf-8") as f:
                for line in f:
                    if line.startswith("REMARK VINA RESULT:"):
                        affinity = float(line.split()[3])
                        if best_affinity is None or affinity < best_affinity:
                            best_affinity = affinity
                            best_path = path
                        break  # only the first (best) MODEL's result line in this file
        except (OSError, IndexError, ValueError) as e:
            print(f"  [-] Could not parse affinity from {path.name}: {e}")

    return best_path, best_affinity


def main():
    BASE_PLIP_DIR.mkdir(parents=True, exist_ok=True)
    ensure_plip_runner()

    receptors = ["wildtype", "t790m"]
    ligands = ["afatinib", "dacomitinib", "erlotinib", "gefitinib", "osimertinib"]

    plip_summary = {}

    print("=== Phase 3: Automated PLIP Non-Covalent Interaction Profiling ===")

    for rec in receptors:
        rec_file_pdb = RECEPTOR_DIR / f"{rec}_clean.pdb"
        rec_file_cif = RECEPTOR_DIR / f"{rec}_clean.cif"
        rec_file = rec_file_pdb if rec_file_pdb.exists() else rec_file_cif

        if not rec_file.exists():
            print(f"\n[!] FATAL: no receptor file found for '{rec}' -- tried both:")
            print(f"      {rec_file_pdb.resolve()}")
            print(f"      {rec_file_cif.resolve()}")
            print(f"    Skipping all {rec} conditions -- every complex built for this "
                  f"receptor would silently contain zero receptor atoms.")
            continue
        elif rec_file.suffix == ".cif":
            print(f"\n[!] FATAL: only a .cif receptor was found for '{rec}': {rec_file.resolve()}")
            print(f"    combine_receptor_and_ligand() reads fixed PDB columns and cannot parse mmCIF.")
            print(f"    Convert it to PDB first (e.g. via OpenBabel or PyMOL: 'save {rec}_clean.pdb') "
                  f"and place it at {rec_file_pdb.resolve()}")
            continue
        else:
            print(f"\n[i] Using receptor file for '{rec}': {rec_file.resolve()} "
                  f"({rec_file.stat().st_size} bytes)")

        for lig in ligands:
            condition_key = f"{rec}_{lig}"
            print(f"\n[+] Profiling Condition: {condition_key.upper()}")
            print("=" * 30)

            pdbqt_dir = RESULTS_DIR / rec / lig / "pdbqt"
            top_pose_pdbqt, top_affinity = find_best_pose_pdbqt(pdbqt_dir, rec, lig)

            if top_pose_pdbqt is None:
                print(f"  [-] No seed PDBQT files with a parseable affinity found in {pdbqt_dir}")
                continue

            print(f"  [i] Best pose across seeds: {top_pose_pdbqt.name} "
                  f"(affinity {top_affinity:.2f} kcal/mol)")

            ligand_pdb = BASE_PLIP_DIR / f"{condition_key}_ligand.pdb"
            complex_pdb = BASE_PLIP_DIR / f"{condition_key}_complex.pdb"

            if not convert_pdbqt_to_pdb(top_pose_pdbqt, ligand_pdb):
                print(f"  [-] Failed to convert {top_pose_pdbqt} to PDB.")
                continue

            combine_receptor_and_ligand(rec_file, ligand_pdb, complex_pdb)

            try:
                xml_out = analyze_with_plip_cli(complex_pdb, condition_key, BASE_PLIP_DIR)

                if xml_out and xml_out.exists():
                    data = parse_plip_xml(xml_out)
                    plip_summary[condition_key] = data
                    print(
                        f"  [Success] H-Bonds: {len(data['h_bonds'])} | "
                        f"Hydrophobic: {len(data['hydrophobic'])} | "
                        f"Total: {data['total_interactions']}"
                    )
                    if data["total_interactions"] == 0:
                        diagnose_zero_interactions(xml_out, complex_pdb)
                else:
                    print(f"  [-] XML result generation failed for {condition_key}")
            except Exception as e:
                print(f"  [Error] PLIP analysis failed for {condition_key}: {e}")

    PLIP_JSON_OUT.parent.mkdir(parents=True, exist_ok=True)
    with open(PLIP_JSON_OUT, "w", encoding="utf-8") as f:
        json.dump(plip_summary, f, indent=4)

    print(f"\n[+] Extracted all interactions. Saved JSON summary -> {PLIP_JSON_OUT}")

    print("[+] Organizing PLIP result files into {receptor}/{drug}/ subdirectories...")
    organize_plip_results(BASE_PLIP_DIR, receptors, ligands)
    print("[+] Directory organization complete.")


if __name__ == "__main__":
    main()